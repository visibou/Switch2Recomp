#!/usr/bin/env python3
"""The NVN entries' registry and AAPCS64 adapters, with gen_hle.py's code (pokopia-native, MIT): hle_nvn.c's NVN() lines, the names in
gfx/names.txt, signatures from nvn_protos.h. Everything else that gen_hle.py does belongs to pokopia-native's service layer, which we do not use
(docs/PLAN_NATIVE_GPU.md D1). Run after adding an NVN() entry:   python -I runtime/nvn/gen/gen_nvn.py"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import gen_hle as G
NVN = os.path.dirname(HERE); GFX = os.path.join(NVN, 'gfx')


def main():
    types = G.Types(os.path.join(GFX, 'nvn.h'))
    got = [e for e in G.parse_file(os.path.join(NVN, 'hle_nvn.c'), 'hle_nvn.c', True)]
    for e in got: e.status = 'ported'
    entries = {e.name: e for e in got if e.kind == 'nvn'}
    forced = [e for e in got if e.kind != 'nvn']
    protos = G.parse_protos(os.path.join(GFX, 'nvn_protos.h'))
    for name in [l.strip() for l in open(os.path.join(GFX, 'names.txt')) if l.strip()]:
        if name in entries: continue
        if name in protos:
            ret, params = protos[name]
            entries[name] = G.Entry(name, 'nvn', 'nvn_protos.h', 'NVN entry point', ret, None, params, 0)
        else:
            e = G.Entry(name, 'nvn', 'names.txt', 'NVN entry point', None, None, None, 0); e.sig_known = False
            entries[name] = e
    ports, stubs, reg = [], [], []
    for e in forced + list(entries.values()):
        if e.status == 'ported': ports += G.adapter_ported(e, types) + ['']
        else: stubs += G.adapter_stub(e, types) + ['']
    hdr = '/* Generated by runtime/nvn/gen/gen_nvn.py; do not edit. */\n'
    open(os.path.join(HERE, 'hle_nvn.adapters.inc'), 'w', encoding='utf-8', newline='\n').write(hdr + G.HELPERS + '\n'.join(ports) + '\n')
    e_all = forced + list(entries.values())
    r = [hdr, '#include "hle_registry.h"', '#include "nxrt/rt_abi.h"', '#include "nvn_protos.h"', G.HELPERS]
    r += ['NXRT_API void adapter_%s(NxwGuestCpu *cpu);' % e.name for e in e_all if e.status == 'ported']
    r += stubs + ['const nxrt_hle_entry nxrt_hle_table[] = {']
    for e in e_all:
        r.append('    {%s, NXRT_HLE_NVN, %d, %s, NULL, adapter_%s},' % (G.c_str(e.name), 1 if e.status == 'ported' else 0, G.c_str(e.file), e.name))
    r += ['};', 'const unsigned nxrt_hle_count = %d;' % len(e_all), '']
    open(os.path.join(HERE, 'hle_nvn_registry.gen.c'), 'w', encoding='utf-8', newline='\n').write('\n'.join(r))
    print('gen_nvn: %d entries, %d ported, %d stubs' % (len(e_all), sum(e.status == 'ported' for e in e_all), sum(e.status != 'ported' for e in e_all)))


if __name__ == '__main__':
    main()
