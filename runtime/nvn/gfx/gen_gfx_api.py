#!/usr/bin/env python3
"""The backend contract as data: reads the backend functions declared in gfx_backend.h and nvn_obj.h and writes
gfx_api.h (one X-macro line per function, for the dispatcher and the backend tables) and gfx_rename.h (the macros
that give a backend's definitions its own names). The contract headers are the source; never edit the outputs.

  gen_gfx_api.py <gfx dir> [--check]        (--check: exit 1 when the outputs are out of date)
"""
import os, re, sys

# Declared in nvn_obj.h but implemented by the recording layer (hle_nvn.c), which the backends call
RECORDING_LAYER = {'nvn_ft_tracked', 'nvn_tex_mirror_b2t', 'nvn_tex_mirror_t2t', 'prog_key', 'nvn_new_serial', 'nvn_serial_floor'}
# Backend functions without the gfx_ prefix: their table member gets a short name of its own
MEMBER = {'bf_want_note': 'bf_want', 'xv_test_counts': 'xv_counts'}


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', ' ', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return re.sub(r'^[ \t]*#[^\n]*', ';', s, flags=re.M)   # preprocessor lines end a statement


def split_params(p):
    out, depth, cur = [], 0, ''
    for ch in p:
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
            continue
        depth += ch in '([' ; depth -= ch in ')]'
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def param_type(p, i):
    """the declaration of parameter i under the name a<i>"""
    p = ' '.join(p.split())
    m = re.match(r'^(.*?)(\w+)\s*(\[\d*\])$', p)   # const int crop[4]
    if m:
        return f'{m.group(1).strip()} a{i}{m.group(3)}'
    m = re.match(r'^(.*?[\s*])(\w+)$', p)
    if m and m.group(2) not in ('int', 'void', 'double', 'float', 'unsigned', 'char') and not m.group(2).endswith('_t'):
        return f'{m.group(1).rstrip()} a{i}'
    return f'{p} a{i}'


def functions(path):
    s = strip_comments(open(path, encoding='utf-8').read())
    out = []
    for stmt in s.split(';'):
        stmt = stmt.strip().split('}')[-1].split('{')[-1].strip()
        m = re.fullmatch(r'((?:const\s+)?[A-Za-z_][\w\s\*]*?)\b((?:gfx|bf|xv)_\w+)\s*\(([^()]*)\)', stmt, re.S)
        if not m:
            continue
        ret, name, params = ' '.join(m.group(1).split()), m.group(2), m.group(3).strip()
        if name in RECORDING_LAYER or ret.startswith('typedef'):
            continue
        ps = [] if params in ('', 'void') else split_params(params)
        out.append((ret, name, ps))
    return out


def main():
    d = sys.argv[1]
    check = '--check' in sys.argv
    seen, fns = set(), []
    for h in ('gfx_backend.h', 'nvn_obj.h'):
        for f in functions(os.path.join(d, h)):
            if f[1] not in seen:
                seen.add(f[1]); fns.append(f)
    head = '// Generated by gen_gfx_api.py from gfx_backend.h and nvn_obj.h (the backend contract); do not edit.\n'
    api = [head + '// One line per backend function: GFX_FN(result, table member, contract name, (parameters), (arguments)), GFX_FNV for a void one.', '']
    ren = [head + '// Included first by every source of a backend (after #define GFX_BE <tag>): the backend defines the contract functions under their contract names and', '// gets them as <tag>_<name>; one of its sources then includes gfx_ops_table.h. The dispatcher (gfx_select.c) owns the real names.',
           '#pragma once', '#ifndef GFX_BE', '#error "define GFX_BE (the backend tag, e.g. null or vk) before including gfx_rename.h"', '#endif',
           '#define GFX_BE_CAT_(b, n) b##_##n', '#define GFX_BE_CAT(b, n) GFX_BE_CAT_(b, n)', '#define GFX_BE_NAME(n) GFX_BE_CAT(GFX_BE, n)']
    for ret, name, ps in fns:
        member = MEMBER.get(name, name[4:] if name.startswith('gfx_') else name)
        decl = ', '.join(param_type(p, i) for i, p in enumerate(ps)) or 'void'
        args = ', '.join(f'a{i}' for i in range(len(ps)))
        api.append(f'{"GFX_FNV" if ret == "void" else "GFX_FN"}({ret}, {member}, {name}, ({decl}), ({args}))')
        ren.append(f'#define {name} GFX_BE_NAME({name})')
    out = {'gfx_api.h': '\n'.join(api) + '\n', 'gfx_rename.h': '\n'.join(ren) + '\n'}
    bad = [n for n, t in out.items() if not os.path.exists(os.path.join(d, n)) or open(os.path.join(d, n), encoding='utf-8', newline='').read() != t]
    if check:
        if bad:
            print('gen_gfx_api: out of date: ' + ', '.join(bad), file=sys.stderr)
            return 1
        print(f'gen_gfx_api: up to date ({len(fns)} backend functions)')
        return 0
    for n, t in out.items():
        with open(os.path.join(d, n), 'w', encoding='utf-8', newline='\n') as f:
            f.write(t)
    print(f'gen_gfx_api: {len(fns)} backend functions')
    return 0


if __name__ == '__main__':
    sys.exit(main())
